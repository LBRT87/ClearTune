export type PixelIconName = keyof typeof ICONS;

export function PixelIcon({
  name,
  size = 16,
  className = "",
}: {
  name: PixelIconName;
  size?: number;
  className?: string;
}) {
  const grid = ICONS[name];
  const cells: { x: number; y: number }[] = [];
  grid.forEach((row, y) => {
    row.split("").forEach((ch, x) => {
      if (ch === "#") cells.push({ x, y });
    });
  });

  return (
    <svg
      viewBox="0 0 8 8"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      fill="currentColor"
      className={className}
      aria-hidden="true"
    >
      {cells.map((c) => (
        <rect key={`${c.x}-${c.y}`} x={c.x} y={c.y} width={1} height={1} />
      ))}
    </svg>
  );
}
